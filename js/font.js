const TEXT_COLORS = {
  w: '#ece6d8', y: '#f6cf57', r: '#e0574a', g: '#8fd35a', b: '#6fa8e8', o: '#f29c38',
  p: '#c57ae0', d: '#8a8294', c: '#7fd8e6', s: '#b8b2c2', k: '#0d0a12'
};

const Font = {
  glyphs: {},      // char -> {w, rows:[[bool]]}
  atlas: new Map(), // color -> {canvas, pos:{char:x}}
  LINE: 10,

  init() {
    for (const ch in GLYPHS) {
      const rows = GLYPHS[ch].split('/');
      const w = rows[0].length;
      this.glyphs[ch] = { w, rows: rows.map(r => [...r].map(c => c === '#')) };
    }
  },
  glyph(ch) {
    const g = this.glyphs[ch];
    if (g) return g;
    // fallback: upper/lower case or question mark
    return this.glyphs[ch.toUpperCase()] || this.glyphs[ch.toLowerCase()] || this.glyphs['?'];
  },
  getAtlas(color) {
    let a = this.atlas.get(color);
    if (a) return a;
    const chars = Object.keys(this.glyphs);
    let total = 0;
    for (const ch of chars) total += this.glyphs[ch].w + 1;
    const cv = document.createElement('canvas');
    cv.width = total; cv.height = 8;
    const c = cv.getContext('2d');
    c.fillStyle = color;
    const pos = {};
    let x = 0;
    for (const ch of chars) {
      const g = this.glyphs[ch];
      pos[ch] = x;
      g.rows.forEach((row, ry) => row.forEach((on, rx) => { if (on) c.fillRect(x + rx, ry, 1, 1); }));
      x += g.w + 1;
    }
    a = { canvas: cv, pos };
    this.atlas.set(color, a);
    return a;
  },
  // width ignoring the color codes
  width(str, scale = 1) {
    let w = 0, n = 0;
    for (let i = 0; i < str.length; i++) {
      const ch = str[i];
      if (ch === '^') { i++; continue; }
      if (ch === ' ') { w += 3; n++; continue; }
      w += this.glyph(ch).w; n++;
    }
    return (w + Math.max(0, n - 1)) * scale;
  },
  // draws text; opts: {color, align, shadow, scale, alpha}
  draw(ctx, str, x, y, opts = {}) {
    str = String(str);
    const scale = opts.scale || 1;
    const align = opts.align || 'left';
    let color = opts.color || TEXT_COLORS.w;
    const baseColor = color;
    let w = this.width(str, scale);
    let cx = align === 'center' ? Math.round(x - w / 2) : align === 'right' ? Math.round(x - w) : Math.round(x);
    y = Math.round(y);
    if (opts.alpha !== undefined) { ctx.save(); ctx.globalAlpha *= opts.alpha; }
    if (opts.shadow !== false) {
      const sh = opts.shadowColor || 'rgba(8,5,12,0.85)';
      this._run(ctx, str, cx + scale, y + scale, scale, sh, true);
    }
    this._run(ctx, str, cx, y, scale, color, false, baseColor);
    if (opts.alpha !== undefined) ctx.restore();
    return w;
  },
  _run(ctx, str, x, y, scale, color, fixed, baseColor) {
    let at = this.getAtlas(color);
    for (let i = 0; i < str.length; i++) {
      let ch = str[i];
      if (ch === '^') {
        const code = str[i + 1]; i++;
        if (!fixed) {
          const col = code === 'w' ? baseColor : (TEXT_COLORS[code] || baseColor);
          at = this.getAtlas(col);
        }
        continue;
      }
      if (ch === ' ') { x += 4 * scale; continue; }
      let g = this.glyphs[ch];
      if (!g) { const alt = this.glyph(ch); ch = Object.keys(this.glyphs).find(k => this.glyphs[k] === alt); g = alt; }
      ctx.drawImage(at.canvas, at.pos[ch], 0, g.w, 8, x, y, g.w * scale, 8 * scale);
      x += (g.w + 1) * scale;
    }
  },
  // automatic wrapping, keeps the color codes across lines
  wrap(str, maxW, scale = 1) {
    const out = [];
    for (const para of String(str).split('\n')) {
      const words = para.split(' ');
      let line = '', lastCode = '';
      for (const word of words) {
        const test = line ? line + ' ' + word : word;
        if (this.width(test, scale) > maxW && line) {
          out.push(line);
          line = (lastCode ? '^' + lastCode : '') + word;
        } else line = test;
        const m = word.match(/\^(.)/g);
        if (m) lastCode = m[m.length - 1][1];
      }
      out.push(line);
    }
    return out;
  },
  drawWrapped(ctx, str, x, y, maxW, opts = {}) {
    const lines = this.wrap(str, maxW, opts.scale || 1);
    const lh = opts.lineH || this.LINE * (opts.scale || 1);
    lines.forEach((l, i) => this.draw(ctx, l, x, y + i * lh, opts));
    return lines.length * lh;
  }
};
